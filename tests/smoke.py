"""End-to-end smoke test: serves www/, injects the mock Saf plugin, drives the UI in headless Chromium.
Run: python3 tests/smoke.py   (needs `pip install playwright` and a Chromium)"""
import http.server, threading, functools, os, sys, json
from playwright.sync_api import sync_playwright
root=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
H=functools.partial(http.server.SimpleHTTPRequestHandler,directory=os.path.join(root,'www'))
H.log_message=lambda *a:None
srv=http.server.ThreadingHTTPServer(('127.0.0.1',0),H);threading.Thread(target=srv.serve_forever,daemon=True).start()
url=f'http://127.0.0.1:{srv.server_port}/index.html'
mock=open(os.path.join(root,'tests','mock-saf.js')).read()
fails=[];errs=[]
def ok(c,m):
    print(('PASS ' if c else 'FAIL ')+m)
    if not c:fails.append(m)
with sync_playwright() as p:
    b=p.chromium.launch(executable_path=os.environ.get('CHROME','/opt/pw-browsers/chromium'),args=['--no-sandbox']) if os.path.exists('/opt/pw-browsers/chromium') else p.chromium.launch(args=['--no-sandbox'])
    pg=b.new_page(viewport={'width':412,'height':860});pg.add_init_script(mock);pg.add_init_script("localStorage['cnd.auth.prof']='0'");pg.add_init_script("if(!localStorage['conduint.v1'])localStorage['conduint.v1']='{\"settings\":{\"permAsked\":true,\"autoPerm\":false}}'")
    pg.on('pageerror',lambda e:errs.append(str(e)));pg.on('console',lambda m:m.type=='error' and errs.append(m.text))
    pg.goto(url);pg.evaluate('askedAll=true');pg.evaluate("document.body.classList.remove('nav')")
    names=lambda:pg.eval_on_selector_all('#list .it .nm','e=>e.map(x=>x.textContent)')
    T=lambda:pg.evaluate('Object.keys(__T).filter(k=>k)')
    dlgok=lambda:pg.click('#dk')
    def ctx(name,label):
        pg.locator('#list .it',has=pg.locator('.nm',has_text=name)).first.click(button='right')
        pg.locator('#menu .mi',has_text=label).first.click()
    # connect internal storage through the hint dialog
    pg.click('#burger');pg.locator('#stor .nv').first.click();pg.wait_for_selector('#dlg.on');dlgok();pg.wait_for_selector('#list .it')
    ok(set(names())>={'Docs','Music','readme.txt'},'connect storage and list root: '+str(names()))
    # new folder
    pg.click('#bm');pg.locator('#menu .mi',has_text='New folder').click();pg.fill('#di','Projects');dlgok();pg.wait_for_timeout(150)
    ok('Projects' in names(),'create folder')
    # rename folder, pin first to check pin follows
    ctx('Docs','Pin to top');pg.click('#burger');ok(pg.locator('#pins .nv',has_text='Docs').count()==1,'pin folder');pg.click('#scrim')
    ctx('Docs','Rename');pg.fill('#di','Papers');dlgok();pg.wait_for_timeout(150)
    ok('Papers' in names() and 'Docs' not in names(),'rename folder')
    ok(pg.evaluate('S.pins[0].name')=='Papers','pin follows rename')
    # open folder, select two files, copy, paste into Projects
    pg.locator('#list .it',has=pg.locator('.nm',has_text='Papers')).click();pg.wait_for_selector('#list .it .nm:text("a.txt")')
    ctx('a.txt','Select');pg.locator('#list .it',has=pg.locator('.nm',has_text='b.md')).click()
    ok(pg.locator('#sel .sn').inner_text()=='2 selected','multi-select count')
    pg.screenshot(path=os.environ.get('SHOT2','/tmp/shot2.png'))
    pg.locator('#sel .sb',has_text='Copy').click();ok(pg.locator('#pst.on').count()==1,'paste bar shows')
    pg.click('#crumbs .crumb:first-child');pg.wait_for_selector('#list .it')
    pg.locator('#list .it',has=pg.locator('.nm',has_text='Projects')).click();pg.wait_for_timeout(150);pg.click('#ppaste');pg.wait_for_timeout(250)
    ok({'a.txt','b.md'}<=set(names()),'paste copied files: '+str(names()))
    ok('Papers/a.txt' in T(),'original still there after copy')
    # zip them
    pg.click('#bm');pg.locator('#menu .mi',has_text='Select all').click();pg.locator('#sel .sb',has_text='ZIP').click();pg.fill('#di','bundle.zip');pg.locator('#dx .chip',has_text='Maximum').click();dlgok();pg.wait_for_timeout(250)
    ok('bundle.zip' in names(),'zip created')
    ok(pg.evaluate("__log.find(l=>l[0]==='zip')")[3]==9,'zip level passed to native')
    # extract
    ctx('bundle.zip','Extract here');dlgok();pg.wait_for_timeout(250)
    ok('bundle' in names(),'unzip made folder')
    # delete to bin, restore
    ctx('b.md','Delete');dlgok();pg.wait_for_timeout(300)
    ok('b.md' not in names(),'delete removes from folder')
    ok(pg.evaluate('S.trash.length')==1 and any('.conduint-trash/' in k for k in T()),'item sits in hidden bin folder')
    pg.click('#bm');pg.locator('#menu .mi',has_text='Recycle bin').click();pg.wait_for_selector('#list .it')
    ok(names()==['b.md'],'bin lists the item')
    ctx('b.md','Restore');pg.wait_for_timeout(300)
    ok(pg.evaluate('S.trash.length')==0 and 'Projects/b.md' in T(),'restore puts it back in original folder')
    # duplicate-name delete (collision inside bin)
    pg.evaluate("go(S.mounts[0].id,['Projects'])");pg.wait_for_selector('#list .it')
    ctx('a.txt','Delete');dlgok();pg.wait_for_timeout(250)
    pg.evaluate("go(S.mounts[0].id,['Papers'])");pg.wait_for_selector('#list .it')
    ctx('a.txt','Delete');dlgok();pg.wait_for_timeout(300)
    ok(pg.evaluate('S.trash.length')==2,'two same-name deletes both kept in bin')
    # empty bin
    pg.evaluate("goCat('bin')");pg.wait_for_selector('#list .it');pg.click('#bm');pg.locator('#menu .mi',has_text='empty bin').click();dlgok();pg.wait_for_timeout(300)
    ok(pg.evaluate('S.trash.length')==0 and not any('.conduint-trash/' in k for k in T()),'empty bin deletes for good')
    # cut + paste moves and pins follow
    pg.evaluate("go(S.mounts[0].id,[])");pg.wait_for_selector('#list .it')
    ctx('Papers','Cut');pg.locator('#list .it',has=pg.locator('.nm',has_text='Music')).click();pg.wait_for_timeout(150);pg.click('#ppaste');pg.wait_for_timeout(250)
    ok('Music/Papers' in T() and 'Papers' not in T(),'cut/paste moved folder')
    ok(pg.evaluate('S.pins[0].path.join("/")')=='Music/Papers','pin follows move')
    # open with / share / back button
    pg.evaluate("go(S.mounts[0].id,[])");pg.wait_for_selector('#list .it');ctx('readme.txt','Open with');pg.wait_for_timeout(100)
    ok(pg.evaluate("__log.find(l=>l[0]==='openWith')")==['openWith','readme.txt','text/plain',False],'open with passes text/plain')
    pg.locator('#list .it',has=pg.locator('.nm',has_text='Music')).click();pg.wait_for_timeout(150)
    ok(pg.evaluate('cur.path.join("/")')=='Music','entered Music')
    pg.evaluate('history.back()');pg.wait_for_timeout(250)
    ok(pg.evaluate('cur.path.length')==0,'system back goes up one folder')
    # library view uses native scan
    pg.click('#burger');pg.locator('#lib .nv',has_text='Documents').click();pg.wait_for_timeout(250)
    ok('readme.txt' in names(),'library scan lists documents')
    ok(not pg.evaluate("document.body.innerHTML.includes('.conduint-trash')") ,'trash folder name never shown in UI')

    # ---------- V0.4.0: plus menu, bin at the bottom, permissions, tools ----------
    pg.evaluate("goCat('bin')");pg.wait_for_timeout(150)
    pg.click('#burger');pg.click('#add');pg.wait_for_selector('#menu.on')
    items=pg.eval_on_selector_all('#menu .mi','e=>e.map(x=>x.textContent)')
    ok(items==['External storage (SD card, USB)','Cloud storage','Folder','My documents'],'plus menu: external, cloud, folder, and only what is not added yet: '+str(items))
    ok('Internal storage' not in items,'Internal storage leaves the plus menu once added')
    pg.locator('#menu .mi',has_text='Cloud storage').click();pg.wait_for_selector('#dlg.on')
    ok('Google Drive' in pg.inner_text('#dm'),'cloud dialog lists the installed cloud apps')
    pg.locator('#dx .chip',has_text='Cloud files').click();dlgok();pg.wait_for_timeout(300)
    ok(pg.evaluate("S.mounts.some(m=>m.type==='docs'&&m.docs.length===1)") and 'drive-note.txt' in names(),'cloud files are picked, saved as a storage and listed: '+str(names()))
    ok(pg.evaluate("JSON.parse(localStorage['conduint.v1']).mounts.some(m=>m.type==='docs')"),'cloud storage persists in saved state')
    pg.evaluate("go('internal')");pg.wait_for_timeout(200)
    pg.click('#burger');pg.locator('#stor .nv',has_text='Internal').click(button='right')
    lab=pg.eval_on_selector_all('#menu .mi','e=>e.map(x=>x.textContent)')
    ok(lab==['Rename','Change directory','Remove from Conduint'],'long-press storage offers Rename and Change directory: '+str(lab))
    pg.locator('#menu .mi',has_text='Rename').click();pg.fill('#di','Phone');dlgok();pg.wait_for_timeout(100)
    ok(pg.evaluate("mount('internal').name")=='Phone','storage renamed from the side panel')
    pg.evaluate("go('internal')");pg.wait_for_timeout(150)
    ctx('Music','Pin to top');pg.click('#burger')
    pg.locator('#pins .nv',has_text='Music').click(button='right');pg.locator('#menu .mi',has_text='Rename folder').click()
    pg.fill('#di','Tunes');dlgok();pg.wait_for_timeout(250)
    ok('Tunes' in T() and 'Music' not in T() and pg.evaluate("S.pins.some(p=>p.name==='Tunes')"),'pinned folder renamed on disk from the side panel: '+str(T()))
    pg.evaluate("__perm.allFiles=true");pg.evaluate("goCat('imgs')");pg.wait_for_timeout(300)
    ok('x.jpg' in names(),'library auto-detects files without any storage browsing: '+str(names()))
    pg.click('#bm');pg.wait_for_selector('#menu.on');pg.keyboard.press('Escape');pg.evaluate("hideMenu()")
    pg.evaluate("openSet()");pg.wait_for_selector('#set.on');pg.wait_for_timeout(200)
    pg.locator('#sbody .row',has_text='Wake lock').locator('.chip').click();pg.wait_for_timeout(100)
    ok(pg.evaluate("__log.some(l=>l[0]==='wake'&&l[1]===true)"),'wake lock toggle reaches the native plugin')
    pg.locator('#sbody .row',has_text='Battery optimiser').locator('.chip').click();pg.wait_for_timeout(200)
    ok(pg.evaluate("__perm.battery")==True,'battery optimiser ignore is requested')
    pg.evaluate("document.querySelector('#set').classList.remove('on')")
    pg.click('#burger');pg.click('#add');pg.wait_for_selector('#menu.on');pg.locator('#menu .mi',has_text='My documents').click();pg.wait_for_selector('#dlg.on')
    ok('Documents' in pg.inner_text('#dm') or 'documents' in pg.inner_text('#dm'),'My documents shows its hint dialog')
    pg.click('#dn');pg.wait_for_timeout(100);pg.evaluate("hideMenu()")
    pg.evaluate("__perm.allFiles=false;__perm.battery=false")
    order=pg.eval_on_selector_all('#foot .nv .tx b','e=>e.map(x=>x.textContent)')
    ok(order==['Tools','Settings','Recycle bin'],'recycle bin is the last item at the bottom of the panel: '+str(order))
    pg.click('#navbin');pg.wait_for_timeout(150)
    ok(pg.evaluate('cur.cat')=='bin','bottom Recycle bin opens the bin')
    pg.click('#burger');pg.locator('#foot .nv',has_text='Tools').click();pg.wait_for_selector('#tools.on');pg.wait_for_selector('.tc')
    ok(pg.locator('.tc').count()==12,'tools home shows 12 tools')
    ok(pg.locator('.ban').count()==1,'banner asks for All files access')
    pg.locator('.ban .chip').click();pg.wait_for_timeout(100);pg.evaluate('refreshPerm()');pg.wait_for_selector('.ban',state='detached')
    ok(pg.evaluate("__perm.allFiles")==True,'banner Allow grants all files access')
    card=lambda t:pg.locator('#tools .tc').filter(has=pg.get_by_text(t,exact=True)).first.click()
    rows=lambda:pg.eval_on_selector_all('#tbody .lr .li b','e=>e.map(x=>x.textContent)')
    nsel=lambda:pg.locator('#tbody .lr.sel').count()
    # storage optimizer lists junk, empty folders and cache, all selected
    card('Storage optimizer');pg.wait_for_selector('#tbar.on')
    ok(rows().count('a.tmp')==1 and 'Empty1' in rows() and 'App cache' in rows(),'optimizer lists junk, empty folders and cache: '+str(rows()))
    ok(nsel()==len(rows()),'optimizer selects everything by default')
    pg.click('#tback');pg.wait_for_selector('.tc')
    # junk: delete to bin, check path-based bin entries, restore
    card('Junk files');pg.wait_for_selector('#tbar.on')
    ok(sorted(rows())==['a.tmp','empty.bin','old.log'],'junk finder rows: '+str(rows()))
    pg.click('#tbar .danger2');pg.wait_for_selector('#dlg.on');dlgok();pg.wait_for_selector('#tbody .empty')
    ok(pg.evaluate("S.trash.filter(e=>e.p).length")==3 and not pg.evaluate("'/storage/emulated/0/Download/a.tmp' in __F"),'junk moved to the recycle bin')
    pg.click('#tx');pg.evaluate("goCat('bin')");pg.wait_for_selector('#list .it')
    ok('a.tmp' in names(),'bin view lists tool-deleted items')
    ctx('a.tmp','Restore');pg.wait_for_timeout(300)
    ok(pg.evaluate("'/storage/emulated/0/Download/a.tmp' in __F")==True and pg.evaluate("S.trash.length")==2,'restore brings a tool-deleted file back')
    pg.evaluate("void opEmpty()");pg.wait_for_selector('#dlg.on');dlgok();pg.wait_for_timeout(300)
    ok(pg.evaluate("S.trash.length")==0,'empty bin removes path-based items')
    # duplicates: keeps one per group
    pg.evaluate('openTools()');pg.wait_for_selector('.tc');card('Duplicate finder');pg.wait_for_selector('#tbar.on')
    ok(len(rows())==3 and nsel()==2,'duplicates: 3 copies, 2 selected, 1 kept')
    kept=pg.eval_on_selector('#tbody .lr:not(.sel) .li small','e=>e.textContent')
    ok(kept=='Pictures/copy','oldest copy is the one kept: '+kept)
    pg.locator('#tbar .chip',has_text='Keep').click();kept=pg.eval_on_selector('#tbody .lr:not(.sel) .li small','e=>e.textContent')
    ok(nsel()==2 and kept=='Pictures','keep newest flips the kept copy: '+kept)
    pg.click('#tbar .danger2');pg.wait_for_selector('#dlg.on');dlgok();pg.wait_for_selector('#tbody .empty')
    ok(pg.evaluate("Object.keys(__F).filter(k=>k.includes('.jpg')&&!k.includes('trash')).length")==1,'one copy of the duplicate survives')
    pg.click('#tback');pg.wait_for_selector('.tc')
    # empty folders, orphans (orphans start unselected)
    card('Empty folders');pg.wait_for_selector('#tbar.on');ok(rows()==['Empty1'] and nsel()==1,'empty folder tool: '+str(rows()))
    pg.click('#tback');pg.wait_for_selector('.tc')
    card('Orphan folders');pg.wait_for_selector('#tbar.on');ok(rows()==['com.gone.app'] and nsel()==0,'orphan tool lists uninstalled app folder, unselected')
    pg.locator('#tbody .lr').first.click();ok(nsel()==1,'tapping a row selects it')
    pg.click('#tback');pg.wait_for_selector('.tc')
    card('Large files');pg.wait_for_selector('#tbar.on');ok(rows()==['big.mp4'],'large files tool')
    pg.click('#tback');pg.wait_for_selector('.tc')
    card('Old installers');pg.wait_for_selector('#tbar.on');ok(rows()==['app.apk'],'old installers tool')
    pg.click('#tback');pg.wait_for_selector('.tc')
    card('Storage analyzer');pg.wait_for_selector('#tbody .mtr');ok(pg.locator('#tbody .mtr').count()>=3,'analyzer draws bars')
    pg.click('#tback');pg.wait_for_selector('.tc')
    # RAM and cache
    card('RAM optimizer');pg.wait_for_selector('#dlg.on');dlgok();pg.wait_for_function("document.querySelector('#dtt').textContent==='RAM optimized'")
    ok('Free memory' in pg.inner_text('#dm'),'RAM optimizer shows before and after');dlgok();pg.wait_for_timeout(150)
    ok(['ram'] in pg.evaluate('__log'),'RAM optimizer called native')
    card('Cache cleanup');pg.wait_for_selector('#dlg.on');dlgok();pg.wait_for_timeout(250)
    ok(['cache'] in pg.evaluate('__log'),'cache cleanup called native')
    card("Other apps' cache");pg.wait_for_timeout(100);ok(['settings','apps'] in pg.evaluate('__log'),"other apps' cache opens Android settings")
    # permissions sheet, one tap for all
    pg.evaluate("Object.assign(__perm,{images:false,video:false,audio:false,media:false,allFiles:false,notifications:false})")
    card('Permissions');pg.wait_for_selector('#perm.on');pg.wait_for_selector('#pbody .row')
    ok(pg.locator('#pbody .chip:not([disabled])').count()>=5,'permission sheet lists what is missing')
    pg.locator('#pbody .chip',has_text='Allow everything').click()
    pg.wait_for_function("missing().length===0",timeout=12000)
    pg.wait_for_function("document.querySelector('#pbody').textContent.includes('Everything is allowed')",timeout=3000)
    ok(pg.evaluate("__perm.audio&&__perm.allFiles&&__perm.notifications")==True,'Allow everything grants music, files and notifications')
    pg.click('#px');ok(not pg.evaluate("document.querySelector('#perm').classList.contains('on')"),'permission sheet closes')
    # back button inside tools
    card('Junk files');pg.wait_for_timeout(300);pg.evaluate('history.back()');pg.wait_for_timeout(250)
    ok(pg.evaluate("TV.view")=='home' and pg.evaluate("document.querySelector('#tools').classList.contains('on')"),'back from a tool returns to tools home')
    pg.evaluate('history.back()');pg.wait_for_timeout(250)
    ok(not pg.evaluate("document.querySelector('#tools').classList.contains('on')"),'back again closes tools')
    # first run asks for permissions once
    p2=b.new_page(viewport={'width':412,'height':860});p2.add_init_script(mock);p2.goto(url);p2.wait_for_selector('#perm.on',timeout=4000)
    ok(True,'first run opens the permission sheet');p2.close()
    ok(not errs,'no console errors: '+str(errs[:3]))
    pg.screenshot(path=os.environ.get('SHOT','/tmp/shot.png'))
    b.close()
print('\nFAILED:' if fails else '\nALL PASSED',fails or '')
sys.exit(1 if fails else 0)
