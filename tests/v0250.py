"""V0.25 tests: Shield APK inspector (risk rules, report screen, install gate, copy gate, rules validation, Shield styles).
Run: python3 tests/v0250.py   (needs `pip install playwright` and a Chromium)"""
import http.server, threading, functools, os, json, io, zipfile
from playwright.sync_api import sync_playwright
root=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
H=functools.partial(http.server.SimpleHTTPRequestHandler,directory=os.path.join(root,'www'));H.log_message=lambda *a:None
srv=http.server.ThreadingHTTPServer(('127.0.0.1',0),H);threading.Thread(target=srv.serve_forever,daemon=True).start()
url=f'http://127.0.0.1:{srv.server_port}/index.html'
mock=open(os.path.join(root,'tests','mock-saf.js')).read()
fails=[];errs=[]
def ok(c,m):
    print(('PASS ' if c else 'FAIL ')+m)
    if not c:fails.append(m)
CHROME=os.environ.get('CHROME','/opt/pw-browsers/chromium-1194/chrome-linux/chrome')
OFFLINE=('ERR_NAME_NOT_RESOLVED','ERR_INTERNET_DISCONNECTED','ERR_CONNECTION','ERR_TUNNEL')
def apk_zip():
    b=io.BytesIO()
    with zipfile.ZipFile(b,'w') as z:z.writestr('AndroidManifest.xml','x');z.writestr('classes.dex','dex\n035')
    return b.getvalue()
SG=lambda sha,subj='CN=Real Dev,O=Dev',to=4102444800000:{'sha256':sha,'subject':subj,'issuer':subj,'selfSigned':True,'from':1600000000000,'to':to,'alg':'SHA256withRSA'}
H1='a1'*32;H2='b2'*32;H3='c3'*32
def info(**k):
    d={'ok':True,'pkg':'com.real.app','label':'Real App','verName':'1.2','verCode':12,'targetSdk':34,'minSdk':24,'debuggable':False,'requested':['android.permission.INTERNET'],'binds':[],'signRead':True,'multi':False,'signers':[SG(H1)],'installed':False,'size':3*1048576}
    d.update(k);return d
with sync_playwright() as p:
    b=p.chromium.launch(executable_path=CHROME,args=['--no-sandbox']) if os.path.exists(CHROME) else p.chromium.launch(args=['--no-sandbox'])
    pg=b.new_page(viewport={'width':360,'height':740});pg.set_default_timeout(8000);pg.add_init_script(mock)
    pg.add_init_script("if(!localStorage['conduint.v1'])localStorage['conduint.v1']='{\"settings\":{\"permAsked\":true,\"autoPerm\":false}}'")
    pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.on('console',lambda m:m.type=='error' and not any(o in m.text for o in OFFLINE) and 'Failed to load resource' not in m.text and errs.append('console: '+m.text))
    z=apk_zip()
    pg.route('**/sdcard/**',lambda r:r.fulfill(status=200,body=z,headers={'Content-Type':'application/octet-stream'}))
    pg.goto(url);pg.wait_for_timeout(600);pg.evaluate('askedAll=true')
    ok(not errs,'no script errors on load '+str(errs))
    ok(pg.evaluate("/^V0\\.\\d+\\.\\d+$/.test(VER)"),'version is set')
    ok(pg.evaluate("typeof shApkAnalyze==='function'&&typeof shApkGate==='function'&&typeof shApkPick==='function'"),'inspector functions exist')
    A=lambda i:pg.evaluate("async(i)=>{const r=await shRules();return shApkAnalyze(i,r)}",i)
    has=lambda a,t,s=None:any(t in x['label'] and (s is None or x['sev']==s) for x in a['findings'])
    # --- rules ---
    r=pg.evaluate("shRules().then(r=>({v:r.v,p:r.apk.perms.length,c:r.apk.combos.length,b:r.apk.brands.length}))")
    ok(r['v']==2 and r['p']>=20 and r['c']>=4 and r['b']>=8,'bundled rules carry the apk section '+str(r))
    # --- analysis ---
    a=A(info());ok(not any(x['sev'] in('high','med') for x in a['findings']),'a plain app has no high or medium findings')
    a=A(info(requested=['android.permission.RECEIVE_SMS','android.permission.INTERNET']))
    ok(has(a,'intercept incoming text','high') and has(a,'steal 2-step codes','high'),'SMS plus internet is flagged high')
    a=A(info(binds=['android.permission.BIND_ACCESSIBILITY_SERVICE'],requested=['android.permission.SYSTEM_ALERT_WINDOW']))
    ok(has(a,'accessibility service','high') and has(a,'banking trojans','high'),'accessibility via a service binding plus overlay is flagged high')
    ok(any(p['name']=='BIND_ACCESSIBILITY_SERVICE' and p['bind'] for p in a['perms']),'service-guard permission is listed and marked')
    a=A(info(pkg='com.evil.chat',label='WhatsApp'));ok(has(a,'not the real app','med'),'fake WhatsApp name is flagged')
    a=A(info(pkg='com.whatsapp.w4b',label='WhatsApp Business'));ok(not has(a,'not the real app'),'WhatsApp Business is not flagged')
    a=A(info(pkg='com.whatsapp',label='WhatsApp'));ok(not has(a,'not the real app'),'the real WhatsApp package is not flagged')
    a=A(info(signers=[SG(H1,'CN=Android Debug,O=Android')]));ok(has(a,'debug key','med'),'debug certificate is flagged')
    a=A(info(debuggable=True));ok(has(a,'debuggable','med'),'debuggable build is flagged')
    a=A(info(signers=[SG(H1,to=1000000000000)]));ok(has(a,'has expired','low'),'expired certificate is info')
    a=A(info(installed=True,installedVer='9.0',installedMatch=False));ok(has(a,'different key','high'),'same app id with a different key is high')
    a=A(info(installed=True,installedVer='9.0',installedMatch=True));ok(has(a,'same key','low') and not has(a,'different key'),'genuine update is info')
    a=A(info(signers=[],signRead=True));ok(has(a,'No signing certificate','med'),'unsigned is flagged')
    a=A(info(signers=[],signRead=False));ok(not has(a,'No signing certificate'),'signature not readable is not called unsigned')
    a=A({'ok':False,'size':10});ok(has(a,'could not read this file as an app','med'),'unreadable APK is flagged')
    a=A(info(targetSdk=21,requested=['android.permission.READ_CONTACTS']));ok(has(a,'old Android','med'),'old target with risky permission is flagged')
    a=pg.evaluate("async(i)=>{const r=await shRules();const r2={...r,apk:{...r.apk,certs:{'"+H2+"':'Test malware family'}}};return shApkAnalyze(i,r2)}",info(signers=[SG(H2)]))
    ok(has(a,'known for malware: Test malware family','high') and any(x['hard'] for x in a['findings']),'known-bad signing key is a hard high finding')
    a=pg.evaluate("shApkAnalyze(%s,{v:1})"%json.dumps(info(requested=['android.permission.READ_SMS'])))
    ok(has(a,'read your text messages','high'),'rules without an apk section fall back to the built-in list')
    # --- Shield screen and report ---
    pg.evaluate("openTools().then(tShield)");pg.wait_for_timeout(400)
    ok(pg.locator('#tbody .chip',has_text='Inspect an APK').count()==1,'Shield screen has Inspect an APK')
    EV=info(label='Evil Chat',pkg='com.evil.chat',requested=['android.permission.RECEIVE_SMS','android.permission.INTERNET','android.permission.CAMERA'],binds=['android.permission.BIND_ACCESSIBILITY_SERVICE'],signers=[SG(H2,'CN=Nobody')])
    pg.evaluate("(o)=>{window.__apk={'/sdcard/evil.apk':o[0],'/sdcard/good.apk':o[1]};window.__cache={'mock:/Docs/evil.apk':'/sdcard/evil.apk','mock:/Docs/good.apk':'/sdcard/good.apk'};SAF.pickDocs=async()=>({items:[{name:window.__pickName,uri:'mock:/Docs/'+window.__pickName,dir:false,size:100}]})}",[EV,info(label='Good Notes',pkg='com.good.notes')])
    pg.evaluate("window.__pickName='evil.apk'");pg.click('#tbody .chip:has-text("Inspect an APK")');pg.wait_for_timeout(700)
    t=pg.inner_text('#shres')
    ok('Evil Chat' in t and 'Dangerous signs' in t,'report shows the app name and a dangerous verdict')
    ok('com.evil.chat' in t and 'version 1.2' in t,'report shows package and version')
    ok(H2 in t,'report shows the signing fingerprint')
    ok('Nobody' in t,'report shows who signed it')
    ok(pg.locator('#shres details summary').count()==1 and 'Permissions it asks for (4)' in pg.inner_text('#shres details summary'),'report lists the permissions')
    ok(pg.locator('#shres .shapk.blocked').count()==1,'dangerous report is styled as blocked')
    pg.evaluate("window.__pickName='good.apk'");pg.click('#tbody .chip:has-text("Inspect an APK")');pg.wait_for_timeout(700)
    ok('No risky signs found' in pg.inner_text('#shres') and pg.locator('#shres .shapk.clean').count()==1,'clean app gets the clean verdict')
    pg.evaluate("window.__pickName='notes.txt'");pg.click('#tbody .chip:has-text("Inspect an APK")');pg.wait_for_timeout(300)
    ok('Pick a .apk file' in pg.inner_text('#toast'),'non-APK is refused with a message')
    # Recent shows Warned for the dangerous one
    pg.evaluate("drawShield()");pg.wait_for_timeout(200)
    ok('Warned:' in pg.inner_text('#tbody'),'Recent says Warned (an inspection is not a block)')
    ok(pg.evaluate("shJ(SHN,{}).b||0")==0,'inspecting does not count as a block')
    # --- Shield styles exist ---
    ok(pg.evaluate("getComputedStyle(document.querySelector('.shlg')).borderLeftWidth")=='3px','Shield card styles are loaded')
    pg.evaluate("shFxOn('Scanning…')");pg.wait_for_timeout(300)
    ok(pg.evaluate("getComputedStyle(document.querySelector('#shfx')).position")=='fixed' and pg.evaluate("parseFloat(getComputedStyle(document.querySelector('#shfx')).opacity)")>0.5,'scan effect is a fixed overlay and visible when on')
    pg.evaluate("shFxOff()");pg.wait_for_timeout(300)
    ok(pg.evaluate("parseFloat(getComputedStyle(document.querySelector('#shfx')).opacity)")<0.5,'scan effect hides when off')
    # --- install gate ---
    inst=lambda n,pth:pg.evaluate('(()=>{installApk({name:"%s",path:"%s"});return 1})()'%(n,pth))
    LOG=lambda:pg.evaluate("window.__log.filter(x=>x[0]==='install').length")
    inst("evil.apk","/sdcard/evil.apk");pg.wait_for_timeout(500)
    ok(pg.locator('#dlg.on').count()==1 and 'Shield: check before installing' in pg.inner_text('#dtt'),'dangerous APK asks before installing')
    ok(LOG()==0,'nothing installed while the question is open')
    pg.click('#dn');pg.wait_for_timeout(300);ok(LOG()==0,'cancel stops the install')
    inst("evil.apk","/sdcard/evil.apk");pg.wait_for_timeout(500);pg.click('#dk');pg.wait_for_timeout(300)
    ok(LOG()==1,'Install anyway installs')
    inst("good.apk","/sdcard/good.apk");pg.wait_for_timeout(500)
    ok(pg.locator('#dlg.on').count()==0 and LOG()==2,'a clean APK installs with no question')
    pg.evaluate("localStorage.setItem(SHK,'0')")
    inst("evil.apk","/sdcard/evil.apk");pg.wait_for_timeout(400)
    ok(pg.locator('#dlg.on').count()==0 and LOG()==3,'Shield off: install goes straight through')
    pg.evaluate("localStorage.removeItem(SHK)")
    pg.evaluate("window.__apk['/sdcard/boom.apk']=null;TOOLS.inspectApk=async()=>{throw new Error('boom')};0")
    inst("boom.apk","/sdcard/boom.apk");pg.wait_for_timeout(400)
    ok(pg.locator('#dlg.on').count()==0 and LOG()==4,'if the inspection fails the install carries on')
    # --- copy gate ---
    pg.reload();pg.wait_for_timeout(600);pg.evaluate('askedAll=true')
    pg.evaluate("(o)=>{window.__apk={'/sdcard/evil.apk':o}}",EV)
    pg.evaluate("window.__cache={'mock:/Docs/evil.apk':'/sdcard/evil.apk'}")
    f=pg.evaluate("async()=>{const r=await shRules();return shScanItem({uri:'mock:/Docs/evil.apk',name:'evil.apk',size:100},r)}")
    ok(any(x['label'].startswith('App file: ') for x in f),'copy scan includes the app findings')
    ok(not any(x['sev']=='high' for x in f if x['label'].startswith('App file: ')),'copying a risky app is flagged, not blocked')
    pg.evaluate("window.__apk['/sdcard/evil.apk']=%s"%json.dumps({**EV,'signers':[SG(H3)]}))
    f=pg.evaluate("async(h)=>{const r=await shRules();r.apk={...r.apk,certs:{[h]:'Test malware family'}};return shScanItem({uri:'mock:/Docs/evil.apk',name:'evil.apk',size:100},r)}",H3)
    ok(any(x['sev']=='high' and 'known for malware' in x['label'] for x in f),'copying an app with a known-bad key is blocked')
    # --- rules validation ---
    def chk(o):return pg.evaluate("(o)=>{try{shCheck(o);return 'ok'}catch(e){return e.message}}",o)
    base={'v':3,'apk':{'perms':[{'name':'READ_SMS','label':'x','sev':'high'}],'combos':[{'all':['READ_SMS','INTERNET'],'label':'y','sev':'high'}],'brands':[{'re':'foo','ok':'^com\\.foo','label':'Foo','sev':'med'}],'certs':{H1:'bad'}}}
    ok(chk(base)=='ok','a good apk section passes the update check')
    ok('not a list' in chk({'v':3,'apk':{'perms':{}}}),'apk.perms must be a list')
    ok('permission rule' in chk({'v':3,'apk':{'perms':[{'name':'X'}]}}),'a permission rule needs label and severity')
    ok('combination' in chk({'v':3,'apk':{'combos':[{'all':[],'label':'y'}]}}),'an empty combination is rejected')
    ok('name rule' in chk({'v':3,'apk':{'brands':[{'re':'(bad','ok':'x','label':'Foo','sev':'med'}]}}),'a brand rule with a broken pattern is rejected')
    ok('SHA-256' in chk({'v':3,'apk':{'certs':{'zz':'x'}}}),'a signing key must be SHA-256')
    ok(not errs,'no script errors during the run '+str(errs))
    b.close()
print('\n'+('ALL PASS' if not fails else 'FAILED: '+str(fails)))
raise SystemExit(1 if fails else 0)
